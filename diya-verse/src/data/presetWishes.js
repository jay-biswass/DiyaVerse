/**
 * Normalizes language key to "en" | "hi" | "bn"
 */
export function normalizeLanguageCode(lang = "English") {
  const l = String(lang).toLowerCase();
  if (l.includes("hindi") || l === "hi") return "hi";
  if (l.includes("bengali") || l.includes("bangla") || l === "bn") return "bn";
  return "en";
}

/**
 * Normalizes tone key to "traditional" | "emotional" | "funny" | "professional" | "inspirational"
 */
export function normalizeToneCode(tone = "Traditional") {
  const t = String(tone).toLowerCase().trim();
  if (presetWishes[t]) return t;
  return "traditional";
}

/**
 * Formats a template string by replacing {recipient} and {sender}
 */
export function formatWishText(templateStr, { recipient = "", sender = "", language = "English" } = {}) {
  const langCode = normalizeLanguageCode(language);
  let defaultRecipient = "Loved One";
  if (langCode === "hi") defaultRecipient = "मित्र";
  if (langCode === "bn") defaultRecipient = "প্রিয়জন";

  const cleanRecipient = recipient && recipient.trim() ? recipient.trim() : defaultRecipient;
  let formatted = templateStr.replace(/\{recipient\}/g, cleanRecipient);

  if (sender && sender.trim()) {
    formatted = formatted.replace(/\{sender\}/g, sender.trim());
  } else {
    formatted = formatted.replace(/\{sender\}/g, "");
  }

  return formatted;
}

/**
 * Retrieves a deterministic preset wish (default index 0) for SSR hydration safety
 */
export function getDefaultPresetWish({
  tone = "Traditional",
  language = "English",
  recipient = "",
  sender = "",
  index = 0,
} = {}) {
  const toneCode = normalizeToneCode(tone);
  const langCode = normalizeLanguageCode(language);
  const list = presetWishes[toneCode]?.[langCode] || presetWishes.traditional.en;
  const safeIndex = index >= 0 && index < list.length ? index : 0;
  return formatWishText(list[safeIndex], { recipient, sender, language });
}

/**
 * Retrieves a wish and avoids repeating the currently displayed one if possible
 */
export function getRandomPresetWish({
  tone = "Traditional",
  language = "English",
  recipient = "",
  sender = "",
  currentWish = "",
} = {}) {
  const toneCode = normalizeToneCode(tone);
  const langCode = normalizeLanguageCode(language);

  const list = presetWishes[toneCode]?.[langCode] || presetWishes.traditional.en;

  // Filter out current wish to ensure regenerate always gives a fresh wish
  const candidates = list.filter((templateStr) => {
    const formatted = formatWishText(templateStr, { recipient, sender, language });
    return formatted.trim() !== currentWish.trim();
  });

  const pool = candidates.length > 0 ? candidates : list;
  const selectedTemplate = pool[Math.floor(Math.random() * pool.length)];

  return formatWishText(selectedTemplate, { recipient, sender, language });
}

